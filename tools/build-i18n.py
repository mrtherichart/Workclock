#!/usr/bin/env python3
"""Build bundled (fully offline) dictionaries and Android string resources.

The TSV is maintained in plain Unicode with one source text + four translations per row.
A stable message ID is generated from its English source for the legacy UI; new
messages should use explicit semantic identifiers in i18n.js.
"""
import csv, json, hashlib, re
from pathlib import Path
from xml.sax.saxutils import escape
root = Path(__file__).resolve().parents[1]
path = root/'tools/translation-strings.tsv'
labels = ['en','nl','de','fr','es']
texts = {tag: {} for tag in labels}
originals = {}
for n, row in enumerate(csv.reader(path.open(encoding='utf-8',newline=''),delimiter='\t'),1):
    if n == 1: continue
    if len(row) != 5:
        raise SystemExit(f'Line {n} has {len(row)} columns; expected 5')
    english=row[0]
    if english in originals:
        if originals[english] != row: print(f'Notice: duplicate string on line {n}: {english}')
        continue
    originals[english] = row
    slug = re.sub(r'[^a-z0-9]+','_',english.lower()).strip('_')[:49].rstrip('_') or 'text'
    key=f'legacy.{slug}.{hashlib.sha1(english.encode()).hexdigest()[:7]}'
    for locale, value in zip(labels, row):
        texts[locale][key]=value
out=root/'app/src/main/assets/i18n'
out.mkdir(exist_ok=True)
for tag in labels:
    (out/f'{tag}.json').write_text(json.dumps(texts[tag],ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
# JS bundle required because WebView also uses local file URLs and does not need fetch.
(root/'app/src/main/assets/i18n-catalog.js').write_text('/* Generated by tools/build-i18n.py; edit the TSV source. */\nwindow.__WorkClockCatalog = '+json.dumps(texts,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
# Native Android resources share translations for notification and launcher labels.
native = {
'work_and_travel':'Work and travel',
'persistent_work_alerts':'Persistent work alerts',
'strong_channel_description':'Workplace arrival and departure; vibration only, no sound',
'arrived_home':'Arrived home',
'return_trip_message':'Open WorkClock to complete your return trip.',
'check_started':'Check whether you started work.',
'check_finished':'Check whether you finished work.',
'notification_start_now':'Start now',
'notification_finish_now':'Finish now',
'notification_earlier':'Earlier…',
'notification_not_working':'Not working',
'notification_still_working':'Still working',
'vibration_test_title':'WorkClock vibration test',
'vibration_test_description':'Ten pulses, no repeat reminders.',
'notification_test_message':'Notifications are working on this device.',
}
for tag in labels:
    folder=root/'app/src/main/res'/('values' if tag=='en' else 'values-'+tag)
    folder.mkdir(exist_ok=True)
    values={src:dict(zip(labels,originals[src]))[tag] for src in native.values()}
    rows=['<?xml version="1.0" encoding="utf-8"?>','<resources>','    <string name="app_name">WorkClock</string>']
    for res,src in native.items():
        value=values[src]
        # Android aapt strings need apostrophes escaped; wrap XML double quotation syntax.
        content=escape(value, {'"':'\\"'})
        content=content.replace("'", "\\'")
        rows.append(f'    <string name="{res}">{content}</string>')
    rows.append('</resources>')
    (folder/'strings.xml').write_text('\n'.join(rows)+'\n',encoding='utf-8')
print(f'Built {len(originals)} phrases for {len(labels)} languages, plus Android notifications')
